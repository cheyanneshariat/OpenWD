"""Validate the offline builder's archived seed reader without running models."""

from dataclasses import asdict
import importlib.util
import json
from pathlib import Path
import shutil

import numpy as np
import pytest

from wd_spectra import D6Config


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "build_d6_regression", ROOT / "tools" / "build_d6_regression.py"
)
BUILDER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(BUILDER)
SOURCE = ROOT / "tests" / "data" / "d6_regressions" / "warm_v1"
SOURCE_SEED = SOURCE.with_name(SOURCE.name + "-seed.npz")


@pytest.fixture
def capsule(tmp_path):
    directory = tmp_path / "warm_v1"
    shutil.copytree(SOURCE, directory)
    shutil.copyfile(SOURCE_SEED, directory.with_name("warm_v1-seed.npz"))
    return directory


def rewrite_manifest(directory, mutate):
    path = directory / "manifest.json"
    manifest = json.loads(path.read_text())
    mutate(manifest)
    path.write_text(json.dumps(manifest))


def rewrite_arrays(directory, mutate):
    seed_path = directory.with_name(directory.name + "-seed.npz")
    reference_path = directory / "j1637.npz"
    for path in (seed_path, reference_path):
        with np.load(path, allow_pickle=False) as saved:
            arrays = {key: saved[key].copy() for key in saved.files}
        mutate(arrays)
        np.savez_compressed(path, **arrays)

    def update_checksums(manifest):
        manifest["seed_sha256"] = BUILDER.digest(seed_path)
        manifest["output_sha256"] = BUILDER.digest(reference_path)

    rewrite_manifest(directory, update_checksums)


def test_original_immutable_capsule_decodes_without_trajectory():
    # These are the historical files, not references generated by this test.
    assert BUILDER.digest(SOURCE_SEED) == (
        "97232692b517ee39b660e0d6534ed0e23422e9901a9e9d0d47c6e05185b2a035"
    )
    assert BUILDER.digest(SOURCE / "j1637.npz") == (
        "0b06d1b0e86fad7db60fa266d0eb3d55251ce12bcfcf9037aa86487c78e2d882"
    )
    arrays, manifest, archive = BUILDER.frozen_source(SOURCE, asdict(D6Config()))
    assert set(arrays) == {
        "column_mass", "optical_depth", "base_temperature", "initial_temperature"
    }
    with np.load(SOURCE_SEED, allow_pickle=False) as seed:
        for key in seed.files:
            np.testing.assert_array_equal(arrays[key], seed[key])
    assert archive["manifest_sha256"] == BUILDER.digest(SOURCE / "manifest.json")
    assert archive["reference_commit"] == manifest["reference_commit"]
    assert manifest["cold_start_qualification"] is False


@pytest.mark.parametrize("corrupted_file", ["seed", "reference"])
def test_corrupted_payload_checksum_is_rejected(capsule, corrupted_file):
    path = (
        capsule.with_name(capsule.name + "-seed.npz")
        if corrupted_file == "seed" else capsule / "j1637.npz"
    )
    with path.open("ab") as handle:
        handle.write(b"corrupted archive")
    with pytest.raises(ValueError, match="integrity or configuration mismatch"):
        BUILDER.frozen_source(capsule, asdict(D6Config()))


def test_mismatched_published_configuration_is_rejected():
    config = asdict(D6Config())
    config["effective_temperature"] += 1
    with pytest.raises(ValueError, match="integrity or configuration mismatch"):
        BUILDER.frozen_source(SOURCE, config)


def test_mismatched_archived_source_request_is_rejected(capsule):
    def mutate(manifest):
        manifest["source_request"]["config"]["abundances"]["Fe"] += 0.1

    rewrite_manifest(capsule, mutate)
    with pytest.raises(ValueError, match="integrity or configuration mismatch"):
        BUILDER.frozen_source(capsule, asdict(D6Config()))


@pytest.mark.parametrize("defect", [
    "unverified", "failures", "unmeasured", "failed", "threshold", "nan",
    "empty-required-checks", "incomplete-required-checks",
])
def test_invalid_archived_certificate_is_rejected(capsule, defect):
    def mutate(manifest):
        certificate = manifest["source_cold_certificate"]
        check = certificate["checks"]["local_energy"]
        if defect == "unverified":
            certificate["verified"] = False
        elif defect == "failures":
            certificate["failures"] = ["local_energy"]
        elif defect == "unmeasured":
            check["measured"] = False
        elif defect == "failed":
            check["passed"] = False
        elif defect == "threshold":
            check["value"] = check["tolerance"]
        elif defect == "nan":
            check["value"] = float("nan")
        elif defect == "empty-required-checks":
            certificate["required_checks"] = []
        elif defect == "incomplete-required-checks":
            certificate["required_checks"].remove("local_energy")
            check["measured"] = False
            check["passed"] = False

    rewrite_manifest(capsule, mutate)
    with pytest.raises(ValueError, match="certificate"):
        BUILDER.frozen_source(capsule, asdict(D6Config()))


@pytest.mark.parametrize("defect", ["shape", "negative", "nonfinite"])
def test_invalid_seed_arrays_rejected_despite_valid_checksums(capsule, defect):
    def mutate(arrays):
        if defect == "shape":
            arrays["column_mass"] = arrays["column_mass"][:-1]
        elif defect == "negative":
            arrays["column_mass"][0] = -1
        elif defect == "nonfinite":
            arrays["column_mass"][0] = np.nan

    rewrite_arrays(capsule, mutate)
    with pytest.raises(ValueError, match="positive finite 48-layer arrays"):
        BUILDER.frozen_source(capsule, asdict(D6Config()))


def test_changed_perturbation_rejected_despite_valid_checksums(capsule):
    def mutate(arrays):
        arrays["initial_temperature"] *= 1.001

    rewrite_arrays(capsule, mutate)
    with pytest.raises(AssertionError):
        BUILDER.frozen_source(capsule, asdict(D6Config()))
